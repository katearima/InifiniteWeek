import { expect, test } from "bun:test";
import { cleanup, fields, ok, setup } from "./support.ts";
cleanup();
test("approval journey from empty database: discover, request, admit, publish, mark", async () => {
  const { api, register } = await setup(); const owner = await register("owner"), other = await register("other");
  expect(await api.groups.list({ session: owner.session })).toEqual({ groups: [] });
  const { group } = ok(await api.groups.create({ session: owner.session, name: "MIT", description: "Students", policy: "APPROVAL" }));
  const { event } = ok(await api.events.publish({ session: owner.session, group, ...fields }));
  expect(ok(await api.groups.list({ session: other.session })).groups).toEqual([{ group, name: "MIT", description: "Students", policy: "APPROVAL", member: false, pending: false }]);
  expect(await api.groups.members({ session: other.session, group })).toEqual({ error: "NOT_GROUP_MEMBER" });
  expect(await api.groups.requests({ session: other.session, group })).toEqual({ error: "NOT_GROUP_MEMBER" });
  expect(await api.events.details({ session: other.session, event })).toEqual({ error: "NOT_FOUND" });
  expect(await api.groups.join({ session: other.session, group })).toEqual({ group, status: "PENDING" });
  expect(await api.groups.join({ session: other.session, group })).toEqual({ error: "REQUEST_ALREADY_PENDING" });
  expect(ok(await api.groups.details({ session: other.session, group })).group).toMatchObject({ member: false, pending: true });
  expect(await api.groups.requests({ session: owner.session, group })).toEqual({ requests: [{ user: other.user, username: "other" }] });
  expect(await api.groups.approve({ session: other.session, group, requester: other.user })).toEqual({ error: "APPROVE_NOT_MEMBER" });
  ok(await api.groups.approve({ session: owner.session, group, requester: other.user }));
  expect(await api.groups.approve({ session: owner.session, group, requester: other.user })).toEqual({ error: "APPROVE_REQUEST_NOT_FOUND" });
  expect(ok(await api.groups.details({ session: other.session, group })).group).toMatchObject({ member: true, pending: false });
  expect(ok(await api.events.details({ session: other.session, event })).event.event).toBe(event);
  ok(await api.events.publish({ session: other.session, group, ...fields }));
  ok(await api.plans.mark({ session: other.session, event, intent: "GOING" }));
  expect(ok(await api.plans.list({ session: other.session })).events).toHaveLength(1);
});
test("reject, policy opening, last-member admission, and empty-group rejoining", async () => {
  const { api, register } = await setup(); const owner = await register("owner"), other = await register("other"), third = await register("third");
  const { group } = ok(await api.groups.create({ session: owner.session, name: "MIT", description: "", policy: "APPROVAL" }));
  ok(await api.groups.join({ session: other.session, group }));
  ok(await api.groups.reject({ session: owner.session, group, requester: other.user }));
  expect(await api.groups.reject({ session: owner.session, group, requester: other.user })).toEqual({ error: "REJECT_REQUEST_NOT_FOUND" });
  ok(await api.groups.join({ session: other.session, group }));
  ok(await api.groups.join({ session: third.session, group }));
  ok(await api.groups.policy({ session: owner.session, group, policy: "OPEN" }));
  expect(await api.groups.requests({ session: owner.session, group })).toEqual({ requests: [] });
  const roster = [{ user: owner.user, username: "owner" }, { user: other.user, username: "other" }, { user: third.user, username: "third" }].sort((a, b) => a.user.localeCompare(b.user));
  expect(await api.groups.members({ session: owner.session, group })).toEqual({ members: roster });
  for (const who of [other, third]) ok(await api.groups.leave({ session: who.session, group }));
  ok(await api.groups.policy({ session: owner.session, group, policy: "APPROVAL" }));
  ok(await api.groups.join({ session: other.session, group }));
  ok(await api.groups.leave({ session: owner.session, group }));
  expect(ok(await api.groups.details({ session: other.session, group })).group).toMatchObject({ member: true, pending: false, policy: "OPEN" });
  ok(await api.groups.leave({ session: other.session, group }));
  expect(ok(await api.groups.details({ session: owner.session, group })).group).toMatchObject({ member: false, pending: false, policy: "OPEN" });
  expect(await api.groups.join({ session: owner.session, group })).toEqual({ group, status: "JOINED" });
});
test("departure clears every group intention including canceled marks, and rejoining restores none", async () => {
  const { api, register, instances } = await setup(); const owner = await register("owner"), other = await register("other");
  const { group } = ok(await api.groups.create({ session: owner.session, name: "MIT", description: "", policy: "OPEN" }));
  const { group: separate } = ok(await api.groups.create({ session: other.session, name: "Other", description: "", policy: "OPEN" }));
  expect(ok(await api.groups.list({ session: other.session })).groups.map(row => row.group)).toEqual([group, separate].sort());
  ok(await api.groups.join({ session: other.session, group }));
  const retained = ok(await api.events.publish({ session: other.session, group: separate, ...fields }));
  ok(await api.plans.mark({ session: other.session, event: retained.event, intent: "GOING" }));
  const events = [];
  for (const intent of ["GOING", "INTERESTED", "NOT_GOING"] as const) {
    const { event } = ok(await api.events.publish({ session: owner.session, group, ...fields })); events.push(event);
    ok(await api.plans.mark({ session: other.session, event, intent }));
  }
  ok(await api.plans.mark({ session: owner.session, event: events[0]!, intent: "GOING" }));
  expect(await api.groups.leave({ session: owner.session, group })).toEqual({ error: "ACTIVE_EVENTS_PREVENT_LEAVING" });
  expect(ok(await api.plans.list({ session: owner.session })).events).toHaveLength(1);
  for (const event of events) ok(await api.events.remove({ session: owner.session, event }));
  ok(await api.groups.leave({ session: other.session, group }));
  for (const event of events) expect(await instances.EventMarking._getMarksByEvent({ event })).not.toContainEqual(expect.objectContaining({ user: other.user }));
  expect(ok(await api.plans.list({ session: other.session })).events.map(row => row.event)).toEqual([retained.event]);
  expect(await api.groups.leave({ session: other.session, group })).toEqual({ error: "LEAVE_NOT_MEMBER" });
  ok(await api.groups.join({ session: other.session, group }));
  expect(ok(await api.plans.list({ session: other.session })).events.map(row => row.event)).toEqual([retained.event]);
  ok(await api.groups.leave({ session: owner.session, group }));
});
test("unknown groups refuse and corrupt roster/request usernames cause opaque failures", async () => {
  const { api, register, database } = await setup(); const owner = await register("owner"), other = await register("other");
  const { group } = ok(await api.groups.create({ session: owner.session, name: "MIT", description: "", policy: "APPROVAL" }));
  const missing = "missing" as typeof group;
  expect(await api.groups.details({ session: owner.session, group: missing })).toEqual({ error: "NOT_FOUND" });
  expect(await api.groups.members({ session: owner.session, group: missing })).toEqual({ error: "NOT_FOUND" });
  expect(await api.groups.requests({ session: owner.session, group: missing })).toEqual({ error: "NOT_FOUND" });
  expect(await api.groups.leave({ session: owner.session, group: missing })).toEqual({ error: "LEAVE_GROUP_NOT_FOUND" });
  expect(await api.groups.leave({ session: other.session, group })).toEqual({ error: "LEAVE_NOT_MEMBER" });
  ok(await api.groups.join({ session: other.session, group }));
  await database.collection("registering.users").deleteOne({ _id: other.user as never });
  expect(await api.groups.requests({ session: owner.session, group })).toMatchObject({ error: "INTERNAL_ERROR" });
  ok(await api.groups.policy({ session: owner.session, group, policy: "OPEN" }));
  expect(await api.groups.members({ session: owner.session, group })).toMatchObject({ error: "INTERNAL_ERROR" });
});
